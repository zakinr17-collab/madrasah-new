import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const root = process.cwd();
const sourceDir = path.join(root, 'src');
const sourceFiles = fs.readdirSync(sourceDir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && /\.(?:js|jsx|ts|tsx)$/i.test(entry.name) && !/\.bak$/i.test(entry.name))
  .map((entry) => path.join(sourceDir, entry.name));

const files = [path.join(root, 'index.html'), ...sourceFiles]
  .filter((file) => fs.existsSync(file));

const allowedCalls = new Set([
  'alert', 'confirm', 'prompt',
  'parseInt', 'parseFloat', 'isNaN', 'isFinite',
  'setTimeout', 'clearTimeout', 'setInterval', 'clearInterval',
  'requestAnimationFrame', 'cancelAnimationFrame',
  'encodeURIComponent', 'decodeURIComponent',
  'atob', 'btoa', 'fetch', 'print', 'close',
  // These two belong to the self-contained PPT HTML document generated by
  // modulAjarModule.js; that document defines them inside its own <script>.
  'prev', 'next'
]);

function isWindowLike(node) {
  return ts.isIdentifier(node) && (node.text === 'window' || node.text === 'globalThis');
}

function collectGlobalExports(file, text, globalExports) {
  if (file.endsWith('.html')) return;

  const source = ts.createSourceFile(
    file,
    text,
    ts.ScriptTarget.Latest,
    true,
    file.endsWith('.tsx') ? ts.ScriptKind.TSX : (file.endsWith('.ts') ? ts.ScriptKind.TS : ts.ScriptKind.JS)
  );

  function visit(node) {
    if (
      ts.isBinaryExpression(node) &&
      node.operatorToken.kind === ts.SyntaxKind.EqualsToken
    ) {
      const left = node.left;
      if (ts.isPropertyAccessExpression(left) && isWindowLike(left.expression)) {
        globalExports.add(left.name.text);
      } else if (
        ts.isElementAccessExpression(left) &&
        isWindowLike(left.expression) &&
        left.argumentExpression &&
        ts.isStringLiteralLike(left.argumentExpression)
      ) {
        globalExports.add(left.argumentExpression.text);
      }
    }

    if (
      ts.isCallExpression(node) &&
      ts.isPropertyAccessExpression(node.expression) &&
      ts.isIdentifier(node.expression.expression) &&
      node.expression.expression.text === 'Object' &&
      node.expression.name.text === 'assign' &&
      node.arguments.length >= 2 &&
      isWindowLike(node.arguments[0]) &&
      ts.isObjectLiteralExpression(node.arguments[1])
    ) {
      for (const prop of node.arguments[1].properties) {
        if (ts.isShorthandPropertyAssignment(prop)) {
          globalExports.add(prop.name.text);
        } else if (
          ts.isPropertyAssignment(prop) ||
          ts.isMethodDeclaration(prop) ||
          ts.isGetAccessorDeclaration(prop) ||
          ts.isSetAccessorDeclaration(prop)
        ) {
          if (ts.isIdentifier(prop.name) || ts.isStringLiteralLike(prop.name)) {
            globalExports.add(prop.name.text);
          }
        }
      }
    }

    ts.forEachChild(node, visit);
  }

  visit(source);
}

function collectStringFragments(file, text) {
  if (file.endsWith('.html')) return [{ text, offset: 0 }];

  const source = ts.createSourceFile(
    file,
    text,
    ts.ScriptTarget.Latest,
    true,
    file.endsWith('.tsx') ? ts.ScriptKind.TSX : (file.endsWith('.ts') ? ts.ScriptKind.TS : ts.ScriptKind.JS)
  );
  const fragments = [];

  function visit(node) {
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
      fragments.push({ text: node.text, offset: node.getStart(source) });
    } else if (ts.isTemplateExpression(node)) {
      let combined = node.head.text;
      for (const span of node.templateSpans) {
        combined += '__EXPR__' + span.literal.text;
      }
      fragments.push({ text: combined, offset: node.getStart(source) });
    }
    ts.forEachChild(node, visit);
  }

  visit(source);
  return fragments;
}

function callsFromHandler(handler) {
  const wrapper = `function __inlineHandler(event) {\n${handler}\n}`;
  const source = ts.createSourceFile(
    'inline-handler.js',
    wrapper,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.JS
  );

  const calls = new Set();
  function visit(node) {
    if (ts.isCallExpression(node)) {
      const callee = node.expression;
      if (ts.isIdentifier(callee)) {
        calls.add(callee.text);
      } else if (
        ts.isPropertyAccessExpression(callee) &&
        isWindowLike(callee.expression)
      ) {
        calls.add(callee.name.text);
      } else if (
        ts.isElementAccessExpression(callee) &&
        isWindowLike(callee.expression) &&
        callee.argumentExpression &&
        ts.isStringLiteralLike(callee.argumentExpression)
      ) {
        calls.add(callee.argumentExpression.text);
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
  return [...calls];
}

const fileTexts = new Map(files.map((file) => [file, fs.readFileSync(file, 'utf8')]));
const globalExports = new Set();

for (const [file, text] of fileTexts) {
  collectGlobalExports(file, text, globalExports);
}

const attrPattern = /\bon(?:click|change|submit|input|blur|focus|keydown|keyup|mouseenter|mouseleave)\s*=\s*(["'])([\s\S]*?)\1/gi;
const problems = [];

for (const [file, text] of fileTexts) {
  for (const fragment of collectStringFragments(file, text)) {
    attrPattern.lastIndex = 0;
    let match;
    while ((match = attrPattern.exec(fragment.text))) {
      const handler = match[2].trim();
      if (!handler) continue;

      for (const call of callsFromHandler(handler)) {
        if (allowedCalls.has(call) || globalExports.has(call)) continue;
        problems.push({
          file: path.relative(root, file).replaceAll(path.sep, '/'),
          call,
          handler: handler.replace(/\s+/g, ' ').slice(0, 220)
        });
      }
    }
  }
}

const unique = [];
const seen = new Set();
for (const problem of problems) {
  const key = `${problem.file}::${problem.call}::${problem.handler}`;
  if (seen.has(key)) continue;
  seen.add(key);
  unique.push(problem);
}

if (unique.length > 0) {
  console.error('Inline-handler global audit failed. These handlers call functions that are not exposed on window/globalThis:');
  for (const item of unique) {
    console.error(`- ${item.file}: ${item.call}()  <=  ${item.handler}`);
  }
  process.exit(1);
}

console.log(`Inline-handler global audit passed: ${globalExports.size} global handlers/values checked across ${files.length} frontend files.`);
